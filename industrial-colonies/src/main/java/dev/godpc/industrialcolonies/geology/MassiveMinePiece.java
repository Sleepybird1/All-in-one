package dev.godpc.industrialcolonies.geology;

import net.minecraft.core.BlockPos;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.*;
import net.minecraft.world.level.chunk.ChunkGenerator;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.levelgen.structure.*;
import net.minecraft.world.level.levelgen.structure.pieces.StructurePieceSerializationContext;

/** Saved association and mine-only access node. The deposit itself is generated by CARVERS. */
public final class MassiveMinePiece extends StructurePiece {
    private MassiveDepositGeometry.Body body;
    private final MiningScanScope continentScope;
    private final boolean compactChamber;
    private final String family;
    private final int regionX,regionZ;
    public MassiveMinePiece(BoundingBox room,MassiveDeposits.Deposit deposit) {
        super(MineshaftVeins.MASSIVE_MARKER.get(),0,new BoundingBox(room.minX(),room.minY(),room.minZ(),room.maxX(),room.maxY(),room.maxZ()));
        body=deposit.body();continentScope=null;compactChamber=false;family=deposit.plan().id();regionX=deposit.plan().candidate().regionX();regionZ=deposit.plan().candidate().regionZ();
    }
    /** Explicitly admitted finite occurrence; caller owns mine siting, never manufactures ore. */
    public MassiveMinePiece(BoundingBox room,MiningScanScope scope) {
        this(room,scope,false);
    }
    public MassiveMinePiece(BoundingBox room,MiningScanScope scope,boolean compactChamber) {
        super(MineshaftVeins.MASSIVE_MARKER.get(),0,new BoundingBox(room.minX(),room.minY(),room.minZ(),room.maxX(),room.maxY(),room.maxZ()));
        if(!scope.isContinent())throw new IllegalArgumentException("Finite continent scope required");
        continentScope=scope;this.compactChamber=compactChamber;body=null;family=scope.family();regionX=scope.regionX();regionZ=scope.regionZ();
        if(compactChamber)requireChamber();
    }
    public MassiveMinePiece(StructurePieceSerializationContext context,CompoundTag tag) {
        super(MineshaftVeins.MASSIVE_MARKER.get(),tag);
        if(tag.getInt("GeometryVersion")==2||tag.getInt("GeometryVersion")==3){
            if(!tag.contains("ContinentScope",net.minecraft.nbt.Tag.TAG_COMPOUND))throw new IllegalArgumentException("Missing finite mine scope");
            continentScope=MiningScopeTags.load(tag.getCompound("ContinentScope"));
            if(!continentScope.isContinent())throw new IllegalArgumentException("Finite mine requires continent scope");
            compactChamber=tag.getInt("GeometryVersion")==3;
            body=null;family=continentScope.family();regionX=continentScope.regionX();regionZ=continentScope.regionZ();if(compactChamber)requireChamber();return;
        }
        if(tag.getInt("GeometryVersion")!=1||tag.contains("ContinentScope"))throw new IllegalArgumentException("Unsupported massive mine geometry");
        continentScope=null;compactChamber=false;
        body=new MassiveDepositGeometry.Body(tag.getLong("DepositSeed"),tag.getDouble("CenterX"),tag.getDouble("CenterY"),tag.getDouble("CenterZ"),tag.getDouble("RadiusX"),tag.getDouble("RadiusY"),tag.getDouble("RadiusZ"));
        family=tag.getString("Family");regionX=tag.getInt("RegionX");regionZ=tag.getInt("RegionZ");
    }
    public MassiveDepositGeometry.Body body(){if(body==null)throw new IllegalStateException("Finite occurrence is not a massive field");return body;}
    public String family(){return family;}
    public boolean compactChamber(){return compactChamber;}
    private void requireChamber(){
        var b=getBoundingBox();
        if(b.getXSpan()!=5||b.getYSpan()!=4||b.getZSpan()!=5||!continentScope.enclosesEnvelope(new MassiveDepositGeometry.Bounds(b.minX(),b.minY(),b.minZ(),b.maxX(),b.maxY(),b.maxZ())))
            throw new IllegalArgumentException("Compact chamber must fit original finite voxel body");
    }
    /** Uses the saved deposit, never the movable structure-piece position, as scan identity. */
    public MiningScanScope extractionScope(ServerLevel level) {
        if(continentScope!=null){
            if(!continentScope.dimension().equals(level.dimension().location().toString())||continentScope.minBuildY()!=level.getMinBuildHeight()||continentScope.maxBuildYExclusive()!=level.getMaxBuildHeight())throw new IllegalArgumentException("Saved finite mine belongs to another level or build interval");
            return continentScope;
        }
        return new MiningScanScope(level.dimension().location().toString(),family,regionX,regionZ,
                body,level.getMinBuildHeight(),level.getMaxBuildHeight());
    }
    @Override protected void addAdditionalSaveData(StructurePieceSerializationContext context,CompoundTag tag) {
        if(continentScope!=null){tag.putInt("GeometryVersion",compactChamber?3:2);tag.put("ContinentScope",MiningScopeTags.save(continentScope));return;}
        tag.putInt("GeometryVersion",1);tag.putLong("DepositSeed",body.seed());
        tag.putDouble("CenterX",body.cx());tag.putDouble("CenterY",body.cy());tag.putDouble("CenterZ",body.cz());
        tag.putDouble("RadiusX",body.rx());tag.putDouble("RadiusY",body.ry());tag.putDouble("RadiusZ",body.rz());
        tag.putString("Family",family);tag.putInt("RegionX",regionX);tag.putInt("RegionZ",regionZ);
    }
    @Override public void move(int x,int y,int z) {
        // Moving the marker never moves/recreates the seed-derived deposit or its reserve identity.
        super.move(x,y,z);
    }
    @Override public void postProcess(WorldGenLevel level,StructureManager manager,ChunkGenerator generator,RandomSource random,BoundingBox clip,ChunkPos owner,BlockPos origin) {
        var room=getBoundingBox();var pos=new BlockPos(room.getCenter().getX(),room.minY()+1,room.getCenter().getZ());
        if(compactChamber){requireChamber();if(!carveChamber(level,clip,pos))return;}
        if(clip.isInside(pos)){
            var scope=extractionScope(level.getLevel());
            if(!scope.isContinent())MiningNodes.place(level,pos,scope);
        }
    }
    /** Only the current native owner is written. Preserve fluid, containers and foreign protected blocks. */
    private boolean carveChamber(WorldGenLevel level,BoundingBox clip,BlockPos node){
        var b=getBoundingBox();
        for(int x=b.minX();x<=b.maxX();x++)for(int y=b.minY();y<=b.maxY();y++)for(int z=b.minZ();z<=b.maxZ();z++){
            var pos=new BlockPos(x,y,z);if(!clip.isInside(pos))continue;var state=level.getBlockState(pos);
            if(state.is(MiningNodes.NODE.get())&&pos.equals(node)&&level.getBlockEntity(pos) instanceof MiningNodes.NodeEntity existing&&continentScope.equals(existing.scope()))continue;
            if(!level.getFluidState(pos).isEmpty()||level.getBlockEntity(pos)!=null)return false;
            var chunk=level.getChunk(x>>4,z>>4,ChunkStatus.CARVERS,false);
            if(!state.isAir()&&!GeologyFeature.replaceable(state)&&(chunk==null||!MiningOreOwnership.owns(chunk,continentScope,pos)))return false;
        }
        for(int x=b.minX();x<=b.maxX();x++)for(int y=b.minY();y<=b.maxY();y++)for(int z=b.minZ();z<=b.maxZ();z++){
            var pos=new BlockPos(x,y,z);if(!clip.isInside(pos)||level.getBlockState(pos).is(MiningNodes.NODE.get()))continue;
            boolean corner=(x==b.minX()||x==b.maxX())&&(z==b.minZ()||z==b.maxZ());
            var state=y==b.minY()||y==b.maxY()?Blocks.OAK_PLANKS.defaultBlockState():corner?Blocks.OAK_LOG.defaultBlockState():Blocks.CAVE_AIR.defaultBlockState();
            if(!level.getBlockState(pos).equals(state)&&(!level.setBlock(pos,state,2)||!level.getBlockState(pos).equals(state)))throw new IllegalStateException("Compact native chamber write failed");
        }
        return true;
    }
}
