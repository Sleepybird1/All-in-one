#!/usr/bin/env python3
"""Create's factory backbone for the manufacturing-first recipe redesign.

The base Create machines should remain obtainable before the late industrial
lines, but they should look like actual machines rather than one- or two-item
vanilla crafts.  Small hardware therefore uses compact, recognizable workbench
layouts.  Only programmed controls and precision logistics use the Copper or
Brass encased manufacturing lines.
"""

from __future__ import annotations

from typing import Any


def _upsert(data: dict[str, Any], recipe: dict[str, Any]) -> None:
    for index, existing in enumerate(data["recipes"]):
        if existing["id"] == recipe["id"]:
            data["recipes"][index] = recipe
            return
    data["recipes"].append(recipe)


def _shaped(
    recipe_id: str,
    *,
    node: str,
    phase: str,
    order: int,
    comment: str,
    pattern: list[str],
    key: dict[str, str],
    output: Any,
    remove: list[str],
) -> dict[str, Any]:
    return {
        "id": recipe_id,
        "node": node,
        "phase": phase,
        "order": order,
        "type": "shaped",
        "comment": comment,
        "pattern": pattern,
        "key": key,
        "output": output,
        "remove": remove,
        "exclusive_output": True,
    }


def _mechanical(
    recipe_id: str,
    *,
    node: str,
    phase: str,
    order: int,
    comment: str,
    pattern: list[str],
    key: dict[str, str],
    output: Any,
    remove: list[str],
) -> dict[str, Any]:
    recipe = _shaped(
        recipe_id,
        node=node,
        phase=phase,
        order=order,
        comment=comment,
        pattern=pattern,
        key=key,
        output=output,
        remove=remove,
    )
    recipe["type"] = "mechanical_crafting"
    return recipe


def _sequence(
    recipe_id: str,
    *,
    node: str,
    phase: str,
    order: int,
    comment: str,
    input_item: str,
    output: Any,
    steps: list[dict[str, str]],
    remove: list[str],
    loops: int = 1,
) -> dict[str, Any]:
    return {
        "id": recipe_id,
        "node": node,
        "phase": phase,
        "order": order,
        "type": "sequenced_assembly",
        "comment": comment,
        "input": input_item,
        "transitional": input_item,
        "output": output,
        "loops": loops,
        "steps": steps,
        "remove": remove,
        "exclusive_output": True,
    }


def _deploy(item: str, machine: str) -> dict[str, str]:
    return {"op": "deploying", "ingredient": item, "machine": machine}


def _press(machine: str) -> dict[str, str]:
    return {"op": "pressing", "machine": machine}


