"""Close native and pending recipe routes around the same metal unit system."""
import json,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'progression/metal-units'
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
cat=read(SRC/'effective.material-catalog.json');policy=cat['policy'];inv=read(ROOT/'progression/ownership/native-inventory.json')
core=set(policy['fluidMetals'].values());tags=inv['tags'];extra={}
def expand(name,kind,seen=None):
    seen=set() if seen is None else seen
    if name in seen:return set()
    seen.add(name);out={'#'+name}
    for v in tags.get(kind+'/'+name,[]):
        v=v.get('id') if isinstance(v,dict) else v
        if isinstance(v,str):out.update(expand(v[1:],kind,seen) if v.startswith('#') else {v})
    return out
for tag in tags:
    if not tag.startswith('item/c:ingots/'):continue
    name=tag.removeprefix('item/c:ingots/')
    for form,amount in [('ingots',100),('nuggets',10),('storage_blocks',900),('plates',100)]:
        for ref in expand('c:'+form+'/'+name,'item'):
            policy['finishedValues'][ref]={'metal':name,'amount':amount}
            if form=='ingots':policy['ingots'][ref]=True
            if form=='nuggets':policy['nuggets'][ref]=True
    for prefix in ('c:','modernfoundry:'):
        for ref in expand(prefix+'molten_'+name,'fluid'):
            if ref in policy['fluidMetals']:continue
            policy['fluidMetals'][ref]=name
            if name not in core:extra[name]=90
# Yellorium has a pack-owned fluid name rather than a molten_* alias.
policy['fluidMetals']['bigreactors:yellorium']='yellorium'
policy['finishedValues']['bigreactors:yellorium_ingot']={'metal':'yellorium','amount':100}
extra['yellorium']=90
# The installed TFMG cast-iron ecosystem uses 144 mB per ingot.
extra['cast_iron']=144
# Native casting establishes aliases whose fluid names differ from the item
# material, notably molten_debris -> netherite_scrap. Without that alias, changing
# scrap/nugget breakdown alone could create a remelting loop.
for entry in inv['recipes'].values():
    data=entry['data']
    if data.get('type') not in ('modernfoundry:casting_table','modernfoundry:casting_basin'):continue
    result=data.get('result',{});feed=data.get('fluid',{})
    if isinstance(result,str):result={'item':result}
    if not isinstance(result,dict) or not isinstance(feed,dict):continue
    ref=result.get('item',result.get('id',('#'+result['tag']) if 'tag' in result else ''))
    if not isinstance(ref,str) or not policy['ingots'].get(ref):continue
    value=policy['finishedValues'].get(ref)
    fluidref=feed.get('fluid',('#'+feed['tag']) if 'tag' in feed else '')
    if not value or not isinstance(fluidref,str) or not fluidref or fluidref in policy['fluidMetals']:continue
    refs=expand(fluidref[1:],'fluid') if fluidref.startswith('#') else {fluidref}
    for alias in refs:policy['fluidMetals'][alias]=value['metal']
    extra[value['metal']]=feed.get('amount',90)/result.get('count',1)
helpers=(ROOT/'tools/material_processing/policy.js').read_text(encoding='utf-8')
helpers=helpers[helpers.index('  function refs('):helpers.index('  event.forEachRecipe')]
script='// priority: -1400\n// Generated by tools/build_metal_unit_closure.py. Metal quantities only.\nServerEvents.recipes(event => {\n'
script+='  var policy = '+json.dumps(policy,separators=(',',':'))+';\n'
script+='  var extra = '+json.dumps(extra)+';\n'
legacy=read(ROOT/'isolated-runtime/semiconductors-01/ownership-effective-recipes.json')
script+='  var legacy = '+json.dumps({rid:True for rid in legacy if rid.startswith('industrial_colonies:')},separators=(',',':'))+';\n'
script+='  var scaled = '+json.dumps(dict.fromkeys(cat['recipes'],True))+';\n'
script+='  var coreForms = '+json.dumps(cat['metals'],separators=(',',':'))+';\n'
script+="  scaled['industrial_colonies:materials/yellorium/molten_alloy']=true; scaled['industrial_colonies:materials/yellorium/ingot_casting']=true;\n"
script+=helpers
script+='''
  var replacements=[],audit=[];
  function normalize(data,fields,direction,totals,id) {
    var changed=false;
    fields.forEach(key=>{
      var nodes=[];fluidNodes(data[key],nodes);
      nodes.forEach(entry=>{
        var node=entry.node,m=entry.metal,amount=node.amount;
        if(totals[m]!==undefined)amount=totals[m];
        else if(!scaled[id] && extra[m]) {
          var unit=id.indexOf('industrial_colonies:')===0?(legacy[id]?1000:100):extra[m];
          amount=amount*100/unit;
        } else if(!scaled[id] && legacy[id])amount=amount/10;
        amount=Math.max(1,direction==='in'?Math.ceil(amount):Math.floor(amount));
        if(node.amount!==amount){node.amount=amount;changed=true;}
      });
    });return changed;
  }
  function process(recipe) {
    try{recipe.serialize();}catch(error){return false;}
    var data=JSON.parse(recipe.json.toString()),id=String(recipe.getId());
    var before=JSON.stringify(data),inStacks=itemStacks(data,'in'),outStacks=itemStacks(data,'out');
    // One ingot breaks into ten nuggets. Casting ten nuggets also costs one ingot.
    if(inStacks.length===1 && outStacks.length===1 && policy.ingots[inStacks[0].ref] && policy.nuggets[outStacks[0].ref]) {
      var a=policy.finishedValues[inStacks[0].ref],b=policy.finishedValues[outStacks[0].ref];
      if(a.metal===b.metal) {
        var result=data.result || (data.results && data.results[0]) || data.output;
        if(result && typeof result==='object')result.count=inStacks[0].count*10;
      }
    }
    // Nine-nugget legacy shortcuts are incompatible with ten-nugget ingots.
    if(inStacks.length && outStacks.length && inStacks.every(s=>policy.nuggets[s.ref]) && outStacks.every(s=>policy.ingots[s.ref])) {
      var tin=materialTotals(inStacks),tout=materialTotals(outStacks);
      if(Object.keys(tout).some(m=>(tin[m] || 0)<tout[m])) {
        var target=outStacks[0],source=inStacks[0],m=policy.finishedValues[target.ref].metal;
        if(outStacks.length===1 && target.count===1 && target.ref.charAt(0)!=='#' && inStacks.every(s=>policy.finishedValues[s.ref].metal===m)) {
          replacements.push({id:id,data:{type:'create:mechanical_crafting',pattern:['AAAAA','AAAAA'],key:{A:source.ref.charAt(0)==='#'?{tag:source.ref.substring(1)}:{item:source.ref}},result:{id:target.ref,count:1},accept_mirrored:true}});
          audit.push({id:id,action:'ten-nugget-consolidation'});
        } else audit.push({id:id,action:'remove-nugget-shortcut'});
        return true;
      }
    }
    // Per-metal totals are appropriate for single-input melting and single-result
    // casting. Mixed chemical reactions retain their original stoichiometric ratios.
    var casting=data.type==='modernfoundry:casting_table'||data.type==='modernfoundry:casting_basin'||data.type==='nuclearcraft:ingot_former';
    var melting=data.type==='modernfoundry:melting'||data.type==='nuclearcraft:melter';
    var modified=normalize(data,['fluid','ingredient','ingredients','input','inputs','fluid_input','fluid_inputs'],'in',casting?materialTotals(outStacks):{},id);
    if(normalize(data,['result','results','output','outputs','fluid_output','fluid_outputs'],'out',melting?materialTotals(inStacks):{},id))modified=true;
    if(modified || before!==JSON.stringify(data)) {
      if(data.type.indexOf('modernfoundry:')===0)data.id=id;
      replacements.push({id:id,data:data});audit.push({id:id,action:'normalize'});return true;
    }
    return false;
  }
  event.forEachRecipe({},recipe=>{if(process(recipe))recipe.remove();});
  event.addedRecipes.removeIf(recipe=>process(recipe));
  replacements.forEach(entry=>event.custom(entry.data).id(entry.id));
  // Core nine-nugget recipes were retired by the earlier material policy before
  // this callback. Provide an exact ten-nugget route without orphaning solid forms.
  Object.keys(coreForms).forEach(m=>{
    var forms=coreForms[m];if(!forms.nugget)return;
    event.custom({type:'create:mechanical_crafting',pattern:['AAAAA','AAAAA'],key:{A:{tag:'c:nuggets/'+m}},result:{id:forms.ingot,count:1},accept_mirrored:true}).id('industrial_colonies:units/'+m+'/ten_nuggets');
  });
  JsonIO.write('kubejs/industrial_metal_unit_audit.json',audit);
  console.info('[Industrial Colonies] 100 mB metal units reconciled '+audit.length+' routes.');
});
'''
(SRC/'unit_policy.js').write_text(script,encoding='utf-8')
(SRC/'closure-policy.json').write_text(json.dumps(policy,indent=2),encoding='utf-8')
shutil.copy2(SRC/'closure-policy.json',ROOT/'isolated-runtime/metal-units-01/closure-policy.json')
shutil.copy2(SRC/'unit_policy.js',ROOT/'isolated-runtime/metal-units-01/kubejs/server_scripts/zzzzz_industrial_metal_units.js')
print('Closure covers',len(set(policy['fluidMetals'].values())),'ingot-tagged materials')
